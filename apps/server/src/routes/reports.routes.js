import ExcelJS from 'exceljs';
import { Router } from 'express';
import { authenticate, requirePermission } from '../middleware/auth.js';
import { asyncHandler, ApiError } from '../utils/errors.js';
import { parseDateRange } from '../utils/validate.js';
import { REPORT_LIST, getReportDefinition, runReport } from '../services/reports.service.js';
import { streamTableReport, fmtMoney, fmtDate, fmtDateTime } from '../services/pdf.service.js';
import { getClinic } from '../services/clinic.service.js';

const router = Router();
router.use(authenticate);

router.get('/', requirePermission('reports.view'), asyncHandler(async (req, res) => {
  const list = REPORT_LIST.map((name) => {
    const def = getReportDefinition(name);
    return { name, title: def.title, permission: def.permission };
  }).filter((r) => r.permission !== 'reports.financial' || req.user.permissions.includes('reports.financial'));
  res.json({ data: list });
}));

router.get('/:name', requirePermission('reports.view'), asyncHandler(async (req, res) => {
  const def = getReportDefinition(req.params.name);
  if (!def) throw ApiError.notFound('Unknown report');
  if (def.permission === 'reports.financial' && !req.user.permissions.includes('reports.financial')) {
    throw ApiError.forbidden('You do not have access to financial reports');
  }

  const { start, end } = parseDateRange(req.query, { defaultDays: 30 });
  const format = String(req.query.format || 'json').toLowerCase();
  const report = await runReport(req.params.name, { start, end, user: req.user });
  const subtitle = `${fmtDate(start)} to ${fmtDate(end)}`;

  if (format === 'csv' || format === 'xlsx' || format === 'pdf') {
    const maxRows = 20000;
    const rows = report.rows.slice(0, maxRows);
    if (format === 'pdf') {
      await streamTableReport({ ...report, rows, subtitle, generatedBy: req.user.fullName, generatedAt: new Date() }, res);
      return;
    }
    const fileName = `${report.name}-${start}-to-${end}.${format}`;
    if (format === 'csv') {
      const lines = [report.columns.map((c) => csvCell(c.label)).join(',')];
      for (const row of rows) {
        lines.push(report.columns.map((c) => csvCell(formatCell(row[c.key], c.format))).join(','));
      }
      res.setHeader('Content-Type', 'text/csv; charset=utf-8');
      res.setHeader('Content-Disposition', `attachment; filename="${fileName}"`);
      res.send('\ufeff' + lines.join('\r\n'));
      return;
    }
    const clinic = await getClinic();
    const clinicTitle = clinic?.name || 'ZhanX DentalCare';
    const workbook = new ExcelJS.Workbook();
    workbook.creator = clinicTitle;
    workbook.created = new Date();
    const sheetName = (report.title || report.name).replace(/[:\\/?*\[\]]/g, ' ').slice(0, 31);
    const sheet = workbook.addWorksheet(sheetName, {
      views: [{ showGridLines: true }]
    });

    const colCount = Math.max(report.columns.length, 4);
    const lastColLetter = String.fromCharCode(64 + Math.min(colCount, 26));

    // 1. Executive Clinic Header
    sheet.mergeCells(`A1:${lastColLetter}1`);
    const titleCell = sheet.getCell('A1');
    titleCell.value = clinicTitle.toUpperCase();
    titleCell.font = { name: 'Segoe UI', size: 14, bold: true, color: { argb: 'FF0F2742' } };
    sheet.getRow(1).height = 24;

    sheet.mergeCells(`A2:${lastColLetter}2`);
    const reportTitleCell = sheet.getCell('A2');
    reportTitleCell.value = `${report.title.toUpperCase()} · EXECUTIVE REPORT`;
    reportTitleCell.font = { name: 'Segoe UI', size: 11, bold: true, color: { argb: 'FF1D6FF5' } };
    sheet.getRow(2).height = 20;

    sheet.mergeCells(`A3:${lastColLetter}3`);
    const subCell = sheet.getCell('A3');
    subCell.value = `Date Window: ${fmtDate(start)} to ${fmtDate(end)}  |  Generated by: ${req.user.fullName || 'Staff'}  |  Timestamp: ${fmtDateTime(new Date())}`;
    subCell.font = { name: 'Segoe UI', size: 9, italic: true, color: { argb: 'FF64748B' } };
    sheet.getRow(3).height = 18;

    sheet.addRow([]);
    sheet.getRow(4).height = 10;

    // 2. Column Headers
    const headerRow = sheet.addRow(report.columns.map((c) => c.label));
    headerRow.height = 24;
    headerRow.eachCell((cell) => {
      cell.font = { name: 'Segoe UI', size: 10, bold: true, color: { argb: 'FFFFFFFF' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0F2742' } };
      cell.alignment = { vertical: 'middle', horizontal: 'center' };
      cell.border = {
        top: { style: 'medium', color: { argb: 'FF0F2742' } },
        bottom: { style: 'medium', color: { argb: 'FF0F2742' } },
        left: { style: 'thin', color: { argb: 'FFCBD5E1' } },
        right: { style: 'thin', color: { argb: 'FFCBD5E1' } }
      };
    });

    const moneyKeys = new Set(report.columns.filter((c) => c.format === 'money').map((c) => c.key));
    const intKeys = new Set(report.columns.filter((c) => c.format === 'int' || c.format === 'number').map((c) => c.key));
    const dateKeys = new Set(report.columns.filter((c) => c.format === 'date').map((c) => c.key));

    const totals = {};
    for (const c of report.columns) {
      if (moneyKeys.has(c.key) || intKeys.has(c.key)) totals[c.key] = 0;
    }

    rows.forEach((row, idx) => {
      const rowValues = report.columns.map((c) => {
        const v = row[c.key];
        if (moneyKeys.has(c.key) || intKeys.has(c.key)) {
          const num = Number(v) || 0;
          totals[c.key] = (totals[c.key] || 0) + num;
          return v === null || v === undefined ? '' : num;
        }
        if (c.format === 'bool') return v ? 'Yes' : 'No';
        if (c.format === 'date') return fmtDate(v);
        return v === null || v === undefined ? '' : v;
      });

      const dataRow = sheet.addRow(rowValues);
      dataRow.height = 20;
      const isEven = idx % 2 === 1;

      dataRow.eachCell({ includeEmpty: true }, (cell, colNumber) => {
        const colDef = report.columns[colNumber - 1];
        cell.font = { name: 'Segoe UI', size: 9.5, color: { argb: 'FF1F2937' } };
        if (isEven) {
          cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF8FAFC' } };
        }
        cell.border = {
          top: { style: 'thin', color: { argb: 'FFE2E8F0' } },
          bottom: { style: 'thin', color: { argb: 'FFE2E8F0' } },
          left: { style: 'thin', color: { argb: 'FFE2E8F0' } },
          right: { style: 'thin', color: { argb: 'FFE2E8F0' } }
        };

        if (colDef) {
          if (moneyKeys.has(colDef.key)) {
            cell.numFmt = '₹ #,##0.00';
            cell.alignment = { vertical: 'middle', horizontal: 'right' };
            if (Number(cell.value) < 0) cell.font = { color: { argb: 'FFB91C1C' }, bold: true };
          } else if (intKeys.has(colDef.key)) {
            cell.numFmt = '#,##0';
            cell.alignment = { vertical: 'middle', horizontal: 'right' };
          } else if (dateKeys.has(colDef.key)) {
            cell.alignment = { vertical: 'middle', horizontal: 'center' };
          } else {
            cell.alignment = { vertical: 'middle', horizontal: 'left' };
          }
        }
      });
    });

    // Summary totals row
    if (Object.keys(totals).length > 0 && rows.length > 0) {
      const totalValues = report.columns.map((c, i) => {
        if (i === 0) return 'TOTAL';
        if (totals[c.key] !== undefined) return totals[c.key];
        return '';
      });
      const totalRow = sheet.addRow(totalValues);
      totalRow.height = 22;
      totalRow.eachCell({ includeEmpty: true }, (cell, colNumber) => {
        const colDef = report.columns[colNumber - 1];
        cell.font = { name: 'Segoe UI', size: 10, bold: true, color: { argb: 'FF0F2742' } };
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE2E8F0' } };
        cell.border = {
          top: { style: 'thin', color: { argb: 'FF94A3B8' } },
          bottom: { style: 'double', color: { argb: 'FF0F2742' } },
          left: { style: 'thin', color: { argb: 'FFCBD5E1' } },
          right: { style: 'thin', color: { argb: 'FFCBD5E1' } }
        };
        if (colDef && moneyKeys.has(colDef.key)) {
          cell.numFmt = '₹ #,##0.00';
          cell.alignment = { vertical: 'middle', horizontal: 'right' };
        } else if (colDef && intKeys.has(colDef.key)) {
          cell.numFmt = '#,##0';
          cell.alignment = { vertical: 'middle', horizontal: 'right' };
        } else if (colNumber === 1) {
          cell.alignment = { vertical: 'middle', horizontal: 'center' };
        }
      });
    }

    // Auto-fit column widths
    report.columns.forEach((c, i) => {
      let maxLen = c.label.length;
      rows.forEach((r) => {
        const val = r[c.key];
        const s = val === null || val === undefined ? '' : String(val);
        if (s.length > maxLen) maxLen = s.length;
      });
      sheet.getColumn(i + 1).width = Math.min(48, Math.max(14, maxLen + 4));
    });

    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', `attachment; filename="${fileName}"`);
    await workbook.xlsx.write(res);
    res.end();
    return;
  }

  const page = Math.max(1, Number.parseInt(req.query.page, 10) || 1);
  const pageSize = Math.min(500, Math.max(10, Number.parseInt(req.query.pageSize, 10) || 100));
  const total = report.rows.length;
  const slice = report.rows.slice((page - 1) * pageSize, page * pageSize);
  res.json({
    data: { ...report, rows: slice, range: { start, end } },
    meta: { page, pageSize, total, totalPages: Math.max(1, Math.ceil(total / pageSize)) }
  });
}));

function formatCell(value, format) {
  if (value === null || value === undefined) return '';
  if (format === 'money') return fmtMoney(value);
  if (format === 'bool') return value ? 'Yes' : 'No';
  if (format === 'date') return fmtDate(value);
  return value;
}

function csvCell(value) {
  const s = value === null || value === undefined ? '' : String(value);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export default router;
